#include <stdio.h>
#include <unistd.h>
#include <sys/wait.h>

int main(void)
{
    pid_t pid = fork();

    if (pid == 0)
    {
        printf("Child process running\n");
        return 0;
    }
    else if (pid > 0)
    {
        wait(NULL);
        printf("Child process finished\n");
    }
    else
    {
        perror("fork");
        return 1;
    }

    return 0;
}





